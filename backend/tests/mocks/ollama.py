import random


class FakeOllamaEmbedder:
    """
    Stands in for `OllamaEmbeddings` in tests, so they don't need a running Ollama.

    Each vector is generated by a random number generator seeded with the text itself, so the
    same text always gets the same vector and different texts get
    different ones. 
    """

    def __init__(self, size: int = 768, fail_after_calls: int | None = None):
        """
        :param size: Vector size, must match the model's vector field.
        :param fail_after_calls: Raise on the call after this many successful calls,
            to simulate Ollama going down mid-run.
        """
        self.size = size
        self.fail_after_calls = fail_after_calls
        self.calls = 0
        self.embedded: list[str] = []

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        if self.fail_after_calls is not None and self.calls >= self.fail_after_calls:
            raise ConnectionError("FakeOllamaEmbedder: simulated Ollama failure")

        self.calls += 1
        self.embedded.extend(texts)
        return [self._vector(text) for text in texts]

    def embed_query(self, text: str) -> list[float]:
        return self.embed_documents([text])[0]

    def _vector(self, text: str) -> list[float]:
        rng = random.Random(text)
        return [rng.uniform(-1.0, 1.0) for _ in range(self.size)]
